-- FIN-01: PostgreSQL (cũng tương thích H2 PostgreSQL mode cho kiểm thử)
CREATE TABLE IF NOT EXISTS departments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(150) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(150) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(60) NOT NULL UNIQUE,
 password_hash VARCHAR(150) NOT NULL,
 full_name VARCHAR(150) NOT NULL,
 email VARCHAR(150) NOT NULL UNIQUE,
 role VARCHAR(30) NOT NULL CHECK (role IN ('USER','APPROVER','ACCOUNTANT','ADMIN','AUDITOR')),
 department_id BIGINT REFERENCES departments(id),
 limit_amount NUMERIC(18,2) NOT NULL DEFAULT 10000000 CHECK (limit_amount >= 0),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Anh dai dien: bo sung an toan cho database da co, khong xoa du lieu
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS avatar_file VARCHAR(90);
CREATE TABLE IF NOT EXISTS expenses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(32) NOT NULL UNIQUE,
 created_by BIGINT NOT NULL REFERENCES app_users(id),
 category_id BIGINT NOT NULL REFERENCES categories(id),
 purpose VARCHAR(1000) NOT NULL,
 payee VARCHAR(200) NOT NULL,
 amount NUMERIC(18,2) NOT NULL CHECK (amount > 0),
 supplier VARCHAR(200) NOT NULL,
 invoice_no VARCHAR(100) NOT NULL,
 invoice_date DATE NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','SUBMITTED','APPROVED','REJECTED','PAYMENT_FAILED','PARTIALLY_PAID','PAID','NEEDS_REVIEW','COMPLETED')),
 submitted_at TIMESTAMP, approved_at TIMESTAMP,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_invoice UNIQUE(supplier, invoice_no)
);
CREATE TABLE IF NOT EXISTS documents (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 expense_id BIGINT NOT NULL REFERENCES expenses(id),
 original_name VARCHAR(255) NOT NULL, stored_name VARCHAR(100) NOT NULL UNIQUE,
 content_type VARCHAR(100) NOT NULL, size_bytes BIGINT NOT NULL,
 uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS approvals (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 expense_id BIGINT NOT NULL REFERENCES expenses(id),
 approver_id BIGINT NOT NULL REFERENCES app_users(id),
 decision VARCHAR(20) NOT NULL CHECK (decision IN ('APPROVED','REJECTED')),
 reason VARCHAR(1000), decided_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS payments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 expense_id BIGINT NOT NULL REFERENCES expenses(id),
 payer_id BIGINT NOT NULL REFERENCES app_users(id),
 reference_code VARCHAR(80) NOT NULL UNIQUE,
 status VARCHAR(15) NOT NULL CHECK (status IN ('SUCCESS','FAILED')),
 note VARCHAR(1000), paid_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Bổ sung thông tin chi trả để đối soát được khoản tiền thực tế kế toán KHAI BÁO trong bản mô phỏng.
-- Không gán tiền cho giao dịch cũ vì không có bằng chứng về số tiền đã xử lý.
ALTER TABLE payments ADD COLUMN IF NOT EXISTS paid_amount NUMERIC(18,2);
ALTER TABLE payments ADD COLUMN IF NOT EXISTS paid_payee VARCHAR(200);
ALTER TABLE payments ADD COLUMN IF NOT EXISTS payment_method VARCHAR(30);
ALTER TABLE payments ADD COLUMN IF NOT EXISTS evidence_reference VARCHAR(100);
-- Thông tin ngân hàng ảo, chỉ phục vụ quy trình mô phỏng.
ALTER TABLE payments ADD COLUMN IF NOT EXISTS bank_name VARCHAR(100);
ALTER TABLE payments ADD COLUMN IF NOT EXISTS bank_account VARCHAR(24);
-- Giữ lịch sử giao dịch sai, nhưng không tính vào số tiền đã chi.
ALTER TABLE payments ADD COLUMN IF NOT EXISTS voided BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE payments ADD COLUMN IF NOT EXISTS void_reason VARCHAR(500);
-- Cập nhật ràng buộc cho các CSDL đã được tạo trước bản vá.
ALTER TABLE expenses DROP CONSTRAINT IF EXISTS expenses_status_check;
ALTER TABLE expenses ADD CONSTRAINT expenses_status_check CHECK (status IN
 ('DRAFT','SUBMITTED','APPROVED','REJECTED','PAYMENT_FAILED','PARTIALLY_PAID','PAID','NEEDS_REVIEW','COMPLETED'));

CREATE TABLE IF NOT EXISTS reconciliations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payment_id BIGINT NOT NULL REFERENCES payments(id),
 expense_id BIGINT NOT NULL REFERENCES expenses(id),
 reconciled_by BIGINT NOT NULL REFERENCES app_users(id),
 result VARCHAR(20) NOT NULL CHECK (result IN ('MATCHED','MISMATCHED')),
 note VARCHAR(1000), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recipient_id BIGINT NOT NULL REFERENCES app_users(id),
 message VARCHAR(500) NOT NULL,
 read_at TIMESTAMP, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT REFERENCES app_users(id),
 entity_type VARCHAR(40) NOT NULL,
 entity_id BIGINT,
 action VARCHAR(40) NOT NULL,
 detail VARCHAR(1000), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_expenses_status ON expenses(status);
CREATE INDEX IF NOT EXISTS idx_expenses_creator ON expenses(created_by);
CREATE INDEX IF NOT EXISTS idx_approval_expense ON approvals(expense_id);
CREATE INDEX IF NOT EXISTS idx_audit_entity ON audit_logs(entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_notification_user ON notifications(recipient_id, read_at);
